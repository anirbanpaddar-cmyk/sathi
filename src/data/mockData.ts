const COMMON_SIZES: ('XS' | 'S' | 'M' | 'L' | 'XL' | 'XXL')[] = ['XS', 'S', 'M', 'L', 'XL', 'XXL'];

const createVariants = (colors: { name: string; hex: string }[]) => {
  const variants = [];
  for (const c of colors) {
    for (const s of COMMON_SIZES) {
      variants.push({
        id: `var-${c.name.toLowerCase().replace(/\s+/g, '-')}-${s.toLowerCase()}`,
        size: s,
        color: c.name,
        colorHex: c.hex,
        stock: Math.floor(Math.random() * 12) + 3,
        inStock: true,
      });
    }
  }
  return variants;
};

